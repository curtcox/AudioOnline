import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const directories = ['src', 'ace', 'vendor', 'icons'];
let assets = ['index.html', 'icon.svg', 'manifest.webmanifest', 'service-worker.js', 'LICENSE'];
async function walk(directory) {
  for (const entry of await fs.readdir(new URL(directory + '/', root), { withFileTypes: true })) {
    const path = directory + '/' + entry.name;
    if (entry.name === '__pycache__' || entry.name.endsWith('.pyc') || entry.name === '.DS_Store') continue;
    if (entry.isDirectory()) await walk(path); else assets.push(path);
  }
}
for (const directory of directories) await walk(directory);
assets = assets.sort();
// Pinned CDN files (Pyodide, numpy, lz-string) are part of "Available offline". Neural voices never are.
const pinned = JSON.parse(await fs.readFile(new URL('scripts/remote-hashes.json', root), 'utf8'));
const remote = Object.keys(pinned);
// Cache Storage can be written by anything on this origin; the service worker serves only bytes matching these hashes.
const hashes = {};
for (const asset of assets) hashes[asset] = createHash('sha256').update(await fs.readFile(new URL(asset, root))).digest('hex');
Object.assign(hashes, pinned);
const version = 'audioonline-' + createHash('sha256').update(JSON.stringify(hashes)).digest('hex').slice(0, 16);
const manifest = { version, assets: [...assets, ...remote], hashes };
const source = '/** Generated by node scripts/update-offline.mjs after changing shipped files. */\nconst OfflineAssets = ' + JSON.stringify(manifest, null, 2) + ";\nif (typeof module !== 'undefined') module.exports = OfflineAssets;\nelse globalThis.OfflineAssets = OfflineAssets;\n";
if (process.argv.includes('--check')) {
  if (await fs.readFile(new URL('offline-assets.js', root), 'utf8').catch(() => '') !== source) throw new Error('Offline asset manifest is stale. Run node scripts/update-offline.mjs.');
} else await fs.writeFile(new URL('offline-assets.js', root), source);
console.log(manifest.version + ': ' + manifest.assets.length + ' files');
